using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace Spludlow.MameAO
{
	/// <summary>
	/// Generates the per-version <c>mame.ini</c>.
	///
	/// Why this exists: the Windows original ships its own MAME build inside
	/// &lt;root&gt;/mame/&lt;version&gt;/ and relies on the process working directory
	/// for every search path. A Linux MAME lives somewhere else entirely
	/// (/usr/games/mame, a Flatpak, a source build), so every path has to be
	/// written down explicitly and absolutely.
	///
	/// The file is written into the version directory and that directory is also
	/// the process working directory when MAME runs, so MAME reads this ini (via
	/// the "." in its inipath) and nothing else.
	/// </summary>
	public static class MameIni
	{
		/// <summary>
		/// Build the ini text. Pure so it can be unit tested without touching a
		/// filesystem. Values are emitted as-is (MAME takes the rest of the line),
		/// paths are expected to be absolute.
		/// </summary>
		public static string Build(MameCoreLayout layout, string hashPath)
		{
			if (layout == null)
				throw new ArgumentNullException(nameof(layout));

			List<string> lines = new List<string>
			{
				"#",
				"# Generated by mame-ao for Linux. Do not edit: it is rewritten on start-up.",
				"# Every path is absolute because this MAME is not installed inside this directory.",
				"#",
				"readconfig                1",
				"writeconfig               0",
				"",
				"#",
				"# CORE SEARCH PATH OPTIONS",
				"#",
				$"homepath                  {layout.CoreDirectory}",
				$"inipath                   {layout.CoreDirectory}",
				$"rompath                   {layout.RomDirectory}",
				$"samplepath                {layout.SampleDirectory}",
				$"artpath                   {layout.ArtDirectory}",
				$"ctrlrpath                 {layout.CtrlrDirectory}",
				$"fontpath                  {layout.FontDirectory}",
				$"cheatpath                 {layout.CheatDirectory}",
				$"crosshairpath             {layout.CrosshairDirectory}",
				$"pluginspath               {layout.PluginDirectory}",
				$"languagepath              {layout.LanguageDirectory}",
				$"swpath                    {layout.SoftwareDirectory}",
			};

			if (string.IsNullOrWhiteSpace(hashPath) == false)
				lines.Add($"hashpath                  {hashPath}");

			lines.AddRange(new[]
			{
				"",
				"#",
				"# CORE OUTPUT DIRECTORY OPTIONS",
				"#",
				$"cfg_directory             {layout.ConfigDirectory}",
				$"nvram_directory           {layout.NvramDirectory}",
				$"input_directory           {layout.InputDirectory}",
				$"state_directory           {layout.StateDirectory}",
				$"snapshot_directory        {layout.SnapshotDirectory}",
				$"diff_directory            {layout.DiffDirectory}",
				$"comment_directory         {layout.CommentDirectory}",
				$"share_directory           {layout.ShareDirectory}",
				"",
			});

			return string.Join("\n", lines);
		}

		/// <summary>
		/// Write the ini atomically (temp + rename) so an interrupted start-up
		/// never leaves half a configuration behind.
		/// </summary>
		public static void Write(MameCoreLayout layout, string hashPath)
		{
			string text = Build(layout, hashPath);
			string tempFilename = layout.IniFilename + ".tmp";

			File.WriteAllText(tempFilename, text, new UTF8Encoding(false));
			File.Move(tempFilename, layout.IniFilename, true);
		}
	}
}
